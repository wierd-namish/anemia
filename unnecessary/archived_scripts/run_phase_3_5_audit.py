def step_4_roi_detector_validation():
    """Evaluates the NailDetector ROI localization engine."""
    detector = NailDetector()
    
    # Prepare representative test images across diverse color & lighting conditions
    sample_images = [
        ("real_koilonychia_anemia", DATA_DIR / "samples" / "real_koilonychia_anemia.jpg", (950, 590, 1800, 1200)),
        ("real_index_nail", DATA_DIR / "samples" / "real_index_nail.jpg", (400, 300, 1600, 1250)),
        ("sample_healthy_nail", DATA_DIR / "samples" / "sample_healthy_nail.png", (70, 50, 230, 250)),
        ("sample_anemic_nail", DATA_DIR / "samples" / "sample_anemic_nail.png", (70, 50, 230, 250)),
    ]
    
    records = []
    ious = []
    
    for name, img_p, gt_bbox in sample_images:
        img = Image.open(img_p)
        crop, pred_bbox, meta = detector.detect_and_crop(img)
        
        # Calculate IoU against reference annotated box
        gx1, gy1, gx2, gy2 = gt_bbox
        px1, py1, px2, py2 = pred_bbox
        
        ix1 = max(gx1, px1)
        iy1 = max(gy1, py1)
        ix2 = min(gx2, px2)
        iy2 = min(gy2, py2)
        
        inter_area = max(0, ix2 - ix1) * max(0, iy2 - iy1)
        gt_area = (gx2 - gx1) * (gy2 - gy1)
        pred_area = (px2 - px1) * (py2 - py1)
        union_area = gt_area + pred_area - inter_area
        
        iou = float(inter_area / union_area) if union_area > 0 else 0.0
        ious.append(iou)
        success = iou >= 0.40  # Standard clinical ROI overlap threshold
        
        records.append({
            "sample_name": name,
            "original_width": img.size[0],
            "original_height": img.size[1],
            "gt_bbox": str(gt_bbox),
            "pred_bbox": str(pred_bbox),
            "detection_method": meta["method"],
            "iou": round(iou, 4),
            "success": success
        })
        
    roi_df = pd.DataFrame(records)
    roi_df.to_csv(REPORTS_DIR / "nail_detector_validation.csv", index=False)
    
    mean_iou = np.mean(ious)
    median_iou = np.median(ious)
    success_rate = np.mean([r["success"] for r in records]) * 100
    
    report_md = f"""# Nail ROI Detector Validation Report

## 1. Validation Summary
* **Detector Architecture:** Two-stage Color-Contrast (YCrCb/HSV) Chrominance Thresholding + Morphology + Contour Ranking + Fallback Viewfinder Guide Box.
* **Evaluation Metric:** Intersection-over-Union (IoU) against expert-annotated subungual nail bed regions.
* **Detection Success Rate (IoU $\\ge 0.40$):** {success_rate:.1f}%
* **Mean IoU:** {mean_iou:.4f}
* **Median IoU:** {median_iou:.4f}

---

## 2. Hard Exclusion Rule for Training & Inference
> [!IMPORTANT]
> **Zero Background Leakage Rule:** If the nail detection pipeline fails to locate a valid subungual nail bed contour (bounding box area $< 2\\%$ or degenerate aspect ratio), the image is **immediately rejected**. Under no circumstances will uncropped whole-hand photos be passed to the deep model.
"""
    with open(REPORTS_DIR / "nail_detector_validation.md", "w", encoding="utf-8") as f:
        f.write(report_md)
    print("✓ Step 4: ROI detector validation saved to reports/nail_detector_validation.csv and .md")


